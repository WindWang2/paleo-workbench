// Prediction task runtime service — the callable closure the Workflow
// branch consumes:
//
//   create task -> validate package/input -> execute -> cancel ->
//   inspect progress -> publish result + provenance + summary
//
// The service owns no UI, no catalog persistence and no scheduler: it
// returns JSON descriptors that the Catalog/Workspace/QGIS branches seam
// into their own stores (integration_seams.hpp).
//
// Cancellation is cooperative: request_cancel() flips the CONV-13 cancel
// seam, which is polled between tile groups, so the partial run keeps its
// on-disk resume markers and a second execute() finishes the volume.

#pragma once

