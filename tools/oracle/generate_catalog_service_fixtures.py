def bundle_asset(svc, name: str) -> str:
    src = TMP / svc.project_path.parent.name / "seed.dat"
    src.parent.mkdir(parents=True, exist_ok=True)
    src.write_bytes(b"bundle-seed")
    version = svc.register_result_asset(
        name=name, type="grid", format="bundle", asset_metadata={},
        source_path=src, stage=DataStage.RAW)
    return version.asset_id


def make_source(name: str, files: dict[str, bytes]) -> Path:
    root = TMP / name / "src"
    root.mkdir(parents=True, exist_ok=True)
    for rel, content in files.items():
        target = root / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)
    return root


def member_view(m: VersionMember) -> dict:
    return {
        "name": m.name, "rel_path": m.rel_path, "member_role": m.member_role,
        "ordinal": m.ordinal, "required": m.required, "sha256": m.sha256,
        "size_bytes": m.size_bytes,
    }


def sec_bundle_roundtrip(oracle: dict) -> None:
    p = proj("bd1")
    svc = py_service_mod.DataCatalogService.open(p, sweep_temp=False)
    asset_id = bundle_asset(svc, "Bundle Asset")
    src = make_source("bd1", {
        "a.txt": b"AAA", "sub/b.txt": b"BBB",
        "sub/deep/c.txt": b"CCC", "z.csv": b"ZZZ",
    })
    spec = VersionMember(rel_path="sub/b.txt", name="custom-b",
                         member_role="index", ordinal=7, required=False)
    version = svc.register_bundle_version(
        asset_id, src, DataStage.DERIVED, member_specs=[spec],
        metadata={"k": "v"})
    oracle["bundle_register_roundtrip"] = {
        "members": [member_view(m) for m in version.members],
        "path": version.path,
        "path_is_layout_dir": version.path.endswith(f"/{version.id}"),
        "size_sum": version.size_bytes,
        "aggregate_matches_recompute": (
            version.sha256 == aggregate_member_sha256(version.members)),
        "source_uri": version.source_uri,
        "source_consumed": False,  # move=False keeps the source
        "metadata": version.metadata,
    }
    report = svc.verify_bundle_integrity(version.id)
    oracle["bundle_verify_verified"] = report
    # tamper + delete → modified/missing
    member_file = svc.member_path(version.id, "a.txt")
    member_file.chmod(0o644)
    member_file.write_bytes(b"XXX")
    gone = svc.member_path(version.id, "z.csv")
    gone.chmod(0o644)
    gone.unlink()
    report2 = svc.verify_bundle_integrity(version.id)
    oracle["bundle_verify_tampered"] = {
        "status": report2["status"],
        "members": [
            {k: v for k, v in m.items() if k in ("name", "status")}
            | ({"actual_sha256": m["actual_sha256"]}
               if "actual_sha256" in m else {})
            for m in report2["members"]
        ],
        "actual_matches_tampered": next(
            m.get("actual_sha256") for m in report2["members"]
            if m["name"] == "a.txt") == sha_bytes(b"XXX"),
    }
    svc.close()


def sec_bundle_names_budget(oracle: dict) -> None:
    p = proj("bd2")
    svc = py_service_mod.DataCatalogService.open(p, sweep_temp=False)
    asset_id = bundle_asset(svc, "Names")

    # spec-vs-spec duplicate name.
    src = make_source("bd2", {"a.txt": b"A", "b.txt": b"B"})
    res = err_of(
        svc.register_bundle_version, asset_id, src, DataStage.DERIVED,
        member_specs=[
            VersionMember(rel_path="a.txt", name="same"),
            VersionMember(rel_path="b.txt", name="same"),
        ])
    # interleaved pool: bare name taken by an earlier auto, rel taken by a
    # spec, numeric suffix ~2 (service_v11.py:270-293).
    src2 = make_source("bd2x", {
        "a.txt": b"A", "keep.txt": b"K", "n.txt": b"N", "sub/n.txt": b"NN",
    })
    v2 = svc.register_bundle_version(
        asset_id, src2, DataStage.DERIVED,
        member_specs=[VersionMember(rel_path="keep.txt", name="n.txt")])
    # bare-vs-rel fallback.
    src3 = make_source("bd2y", {"data.csv": b"D", "sub/data.csv": b"DD"})
    v3 = svc.register_bundle_version(asset_id, src3, DataStage.DERIVED)
    oracle["bundle_naming_pool"] = {
        "duplicate_spec_names_error": res["err"],
        "interleaved": sorted(
            (m.name, m.rel_path) for m in v2.members),
        "interleaved_ordinals": [m.ordinal for m in v2.members],
        "bare_vs_rel": sorted((m.name, m.rel_path) for m in v3.members),
    }
    svc.close()

    # member budget (service_v11.py:259-264): 70 files rejected BEFORE any
    # IO; the source stays intact.
    p3 = proj("bd3")
    svc3 = py_service_mod.DataCatalogService.open(p3, sweep_temp=False)
    asset_id3 = bundle_asset(svc3, "Budget")
    files = {f"f{i:02d}.dat": bytes([i]) for i in range(70)}
    src70 = make_source("bd3", files)
    res3 = err_of(svc3.register_bundle_version, asset_id3, src70,
                  DataStage.DERIVED)
    stage_root = TMP / "bd3" / "bd3.artifacts" / "derived" / asset_id3
    oracle["bundle_budget_reject"] = {
        "error": res3["err"],
        "source_intact": len(list(src70.iterdir())) == 70,
        "no_new_version_dirs": not any(
            d.name != svc3.document.versions[0].id
            for d in stage_root.iterdir()) if stage_root.exists() else True,
        "versions_unchanged": len(svc3.document.versions) == 1,
    }
    svc3.close()

    # rel-path guard messages (service_v11.py:408-415), driven through the
    # public API on a real source dir (validation runs before file checks).
    p4 = proj("bd4")
    svc4 = py_service_mod.DataCatalogService.open(p4, sweep_temp=False)
    asset_id4 = bundle_asset(svc4, "Guard")
    src4 = make_source("bd4", {"ok.bin": b"OK", "a..b": b"DOTS"})
    rejects = []
    for bad in ("", "../outside.shp", "a/../../x", "/abs/x"):
        rejects.append({
            "rel": bad,
            # NOTE: through the public API an empty rel_path normalizes to
            # "." (Path("").as_posix()) and fails the missing-file check
            # instead — the guard's own empty-string branch is pinned via
            # the static validator (controlled touch).
            "err": err_of(
                svc4.register_bundle_version, asset_id4, src4,
                DataStage.DERIVED,
                member_specs=[VersionMember(rel_path=bad, name="x")],
            )["err"],
            "static_err": err_of(
                py_service_v11.DataFabricV11Mixin._validate_member_rel_path,
                bad)["err"],
        })
    accepted = svc4.register_bundle_version(
        asset_id4, src4, DataStage.RAW,
        member_specs=[VersionMember(rel_path="a..b", name="dots-file",
                                    member_role="sidecar")])
    oracle["bundle_relpath_guard"] = {
        "rejects": rejects,
        "literal_dots_accepted": [m.name for m in accepted.members],
    }
    svc4.close()


def sec_bundle_wc(oracle: dict) -> None:
    p = proj("bd5")
    svc = py_service_mod.DataCatalogService.open(p, sweep_temp=False)
    asset_id = bundle_asset(svc, "Cycle")
    src = make_source("bd5", {"a.txt": b"AAA", "sub/b.txt": b"BBB"})
    v1 = svc.register_bundle_version(asset_id, src, DataStage.DERIVED)
    wc_dir = svc.create_bundle_working_copy(v1.id)
    members_copied = sorted(p.name for p in wc_dir.rglob("*"))
    edit = wc_dir / "a.txt"
    edit.write_bytes(b"AAA-edited")
    reused = svc.create_bundle_working_copy(v1.id)
    committed = svc.commit_bundle_working_copy(
        wc_dir, asset_id=asset_id, name="cycle v2", stage=DataStage.DERIVED)
    edited_member = next(m for m in committed.members if m.rel_path == "a.txt")
    oracle["bundle_wc_cycle"] = {
        "wc_dir": str(wc_dir),
        "members_copied": members_copied,
        "reuse_same_dir": reused == wc_dir,
        "new_version_number": committed.version_number,
        "parent": committed.parent_version_ids,
        "edited_sha": edited_member.sha256 == sha_bytes(b"AAA-edited"),
        "source_dir_consumed": not wc_dir.exists(),
        "original_members_intact": all(
            (TMP / "bd5" / m_rel).exists() for m_rel in [
                svc.member_path(v1.id, m).relative_to(TMP / "bd5").as_posix()
                for m in v1.members]),
        "rows_after": wc_rows(svc._index),
    }

    # commit as a NEW asset (asset_id=None names the new asset from the dir).
    src2 = make_source("bd5b", {"x.txt": b"XX"})
    v2 = svc.register_bundle_version(asset_id, src2, DataStage.DERIVED)
    wc2 = svc.create_bundle_working_copy(v2.id)
    committed2 = svc.commit_bundle_working_copy(
        wc2, name="Fresh Bundle Asset", stage=DataStage.DERIVED)
    fresh = svc.get_asset(committed2.asset_id)
    oracle["bundle_wc_new_asset"] = {
        "asset_name": fresh.name,
        "distinct_asset": committed2.asset_id != asset_id,
        "parent": committed2.parent_version_ids,
    }
    svc.close()


def sec_v11_ports(oracle: dict) -> None:
    # ports read side (anonymous synthesis) + migrate_run_ports backfill
    # (service_v11.py:199-210, 745-782).
    p = proj("bd6")
    svc = py_service_mod.DataCatalogService.open(p, sweep_temp=False)
    doc = CatalogDocument()
    doc.assets.append(asset("asset_p", "Ports"))
    doc.versions.extend([
        ver("pvin", "asset_p", 1, path="bd6.artifacts/raw/asset_p/pvin/i.bin"),
        ver("pvout", "asset_p", 2, stage=DataStage.DERIVED,
            path="bd6.artifacts/derived/asset_p/pvout/o.bin"),
    ])
    doc.runs.append(run("pr1", "factor_map", inputs=["pvin"],
                        outputs=["pvout"]))
    doc.runs.append(run("pr2", "custom_op", inputs=["pvin"], outputs=[]))
    svc.document = doc
    svc._invalidate_maps()
    svc._save(DirtySet(
        assets={"asset_p": None}, versions={"pvin": None, "pvout": None},
        runs={"pr1": None, "pr2": None}))
    before = svc.ports_for_run("pr1")
    result = svc.migrate_run_ports()
    after = svc.ports_for_run("pr1")
    again = svc.migrate_run_ports()
    oracle["v11_ports_backfill"] = {
        "before_anonymous": {
            "input": [J(x) for x in before["input"]],
            "output": [J(x) for x in before["output"]],
        },
        "migrate_result": result,
        "after": {
            "input": [J(x) for x in after["input"]],
            "output": [J(x) for x in after["output"]],
        },
        "idempotent": again,
        "unknown_operation_untouched": [
            J(x) for x in svc.ports_for_run("pr2")["input"]],
        "store_run_ports": [
            list(r) for r in rows(svc._index,
                                  "SELECT * FROM run_ports ORDER BY rowid")],
    }
    svc.close()


