def rows(index: CatalogIndex, sql: str, params=()) -> list:
    return index.open().execute(sql, params).fetchall()


def raw_exec(project: Path, sql: str, params=()) -> None:
    """Direct sqlite write against the canonical store (touch #3)."""
    db = py_storage.catalog_dir_for(project) / "catalog.sqlite"
    conn = sqlite3.connect(str(db))
    try:
        with conn:
            conn.execute(sql, params)
    finally:
        conn.close()


def dump(index: CatalogIndex) -> dict:
    """Full deterministic store dump (rowid order; sync_state by key)."""
    out: dict = {}
    conn = index.open()
    for table in (
        "assets", "versions", "runs", "run_inputs", "run_outputs", "run_ports",
        "version_members", "tags", "asset_tags", "version_tags", "lineage",
        "models", "model_versions",
    ):
        out[table] = [list(r) for r in conn.execute(
            f"SELECT * FROM {table} ORDER BY rowid")]
    out["sync_state"] = [
        list(r) for r in conn.execute("SELECT * FROM sync_state ORDER BY key")
    ]
    return out


def sync_state(index: CatalogIndex) -> dict:
    return {
        r["key"]: r["value"]
        for r in rows(index, "SELECT key, value FROM sync_state")
    }


def count(index: CatalogIndex, table: str, where: str = "", params=()) -> int:
    sql = f"SELECT count(*) FROM {table}"
    if where:
        sql += f" WHERE {where}"
    return int(index.open().execute(sql, params).fetchone()[0])


def sha_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def err_of(fn, *args, **kw) -> dict:
    """Run fn, freeze {"ok": result-jsonable} or {"ok": None, "err": str}."""
    try:
        value = fn(*args, **kw)
    except Exception as exc:  # noqa: BLE001 - freeze the real message
        return {"ok": None, "err": str(exc), "type": type(exc).__name__}
    if isinstance(value, Path):
        value = str(value)
    return {"ok": value}


