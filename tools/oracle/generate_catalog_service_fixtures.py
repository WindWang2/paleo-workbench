ID_RE = re.compile(
    r"\b(asset|ver|run|tag|model|mver)_([0-9a-f]{12})(?![0-9a-f])")
WC_RE = re.compile(r"\bwc-([0-9a-f]{12})(?![0-9a-f])")
TS_RE = re.compile(r"\.corrupt-\d{8}-\d{6}-\d{6}")


def freeze(text: str) -> str:
    # {ROOT} covers both the literal mkdtemp path and its resolve()d form
    # (resolve_path / restore flows return resolved paths).
    text = text.replace(str(TMP.resolve()), str(TMP))
    text = text.replace(str(TMP), "{ROOT}")
    counter: dict[str, str] = {}

    def sub(match: re.Match) -> str:
        key = match.group(0)
        if key not in counter:
            counter[key] = f"{match.group(1)}_g{len(counter) + 1}"
        return counter[key]

    text = ID_RE.sub(sub, text)

    def sub_wc(match: re.Match) -> str:
        key = match.group(0)
        if key not in counter:
            counter[key] = f"wc-g{len(counter) + 1}"
        return counter[key]

    text = WC_RE.sub(sub_wc, text)
    text = TS_RE.sub(".corrupt-__TS", text)
    return text


