def sec_restore_windows(oracle: dict) -> None:
    # W1 (tombstone persisted, payload in place) and W2 (payload moved, path
    # save lost) crash windows — driven via partial steps (touch #7) then the
    # public restore_version.
    p, svc, v1, content = wc_setup("tr3", b"restore-payload")
    version = svc.get_version(v1.id)
    original_path = version.path
    svc._tombstone_version(version, "w1")
    svc._save(DirtySet(assets={version.asset_id: None},
                       versions={version.id: None}))
    restored_w1 = svc.restore_version(version.id)
    oracle["restore_w1_inplace"] = {
        "path": restored_w1.path,
        "equals_original": restored_w1.path == original_path,
        "file_restored": (TMP / "tr3" / original_path).exists(),
        "tombstone_cleared": "trash" not in restored_w1.metadata
        and not restored_w1.trashed,
        "current_points_back": svc.get_asset(
            restored_w1.asset_id).current_version_id == restored_w1.id,
    }

    # W2: persist tombstone (path=original), move the payload, LOSE the
    # path-update save, then reopen from the store (reload) and restore —
    # _probe_trash_payload finds the file under trash/{vid}/.
    version = svc.get_version(v1.id)
    original_path = version.path
    svc._tombstone_version(version, "w2")
    svc._save(DirtySet(assets={version.asset_id: None},
                       versions={version.id: None}))
    svc._move_payload_to_trash(version)
    svc._reload_document_locked()  # reopen-after-crash view
    reloaded = svc.get_version(version.id)
    store_row_still_original = reloaded.path == original_path
    restored_w2 = svc.restore_version(version.id)
    oracle["restore_w2_probe"] = {
        "store_path_stale_after_crash": store_row_still_original,
        "restored_path": restored_w2.path,
        "equals_original": restored_w2.path == original_path,
        "file_restored": (TMP / "tr3" / original_path).exists(),
        "trash_dir_empty": not any(
            (TMP / "tr3" / "tr3.artifacts" / "trash" / version.id).iterdir()
        ) if (TMP / "tr3" / "tr3.artifacts" / "trash" / version.id).exists()
        else True,
        "tombstone_cleared": "trash" not in restored_w2.metadata,
    }
    svc.close()


def sec_purge(oracle: dict) -> None:
    # refcount purge on a shared blob + zombie assets + un-trash keep +
    # pending-commit protection + save-failure rollback.
    p = proj("tr4")
    svc = py_service_mod.DataCatalogService.open(p, sweep_temp=False)
    blob_src = TMP / "tr4" / "blob.bin"
    blob_src.parent.mkdir(parents=True, exist_ok=True)
    blob_src.write_bytes(b"purge-shared-blob")
    _, digest = py_storage.place_blob(p, blob_src)
    blob_rel = py_storage.blob_path(p, digest).relative_to(TMP / "tr4").as_posix()
    doc = CatalogDocument()
    doc.assets.extend([
        asset("asset_b1", "Blob One"), asset("asset_b2", "Blob Two"),
        asset("asset_z", "Zombie"), asset("asset_p", "Pending Protected"),
        asset("asset_m", "Mixed", trashed=True, trashed_at=NOW),
    ])
    doc.versions.extend([
        ver("pv_a", "asset_b1", 1, managed=True, path=blob_rel, sha256=digest),
        ver("pv_b", "asset_b2", 1, managed=True, path=blob_rel, sha256=digest,
            trashed=True, trashed_at=NOW),
        ver("pv_dead", "asset_m", 1, trashed=True, trashed_at=NOW,
            path="tr4.artifacts/raw/asset_m/pv_dead/x.bin"),
        ver("pv_live", "asset_m", 2),
    ])
    doc.assets[4].current_version_id = "pv_live"
    doc.tags.append(tag("pt1", "qc"))
    doc.asset_tags.update({"asset_z": ["pt1"], "asset_m": ["pt1"]})
    doc.version_tags["pv_dead"] = ["pt1"]
    svc.document = doc
    svc._invalidate_maps()
    svc._save(DirtySet(
        assets={"asset_b1": None, "asset_b2": None, "asset_z": None,
                "asset_p": None, "asset_m": None},
        versions={"pv_a": None, "pv_b": None, "pv_dead": None, "pv_live": None},
        tags={"pt1": None},
        asset_tags={"asset_z": None, "asset_m": None},
        version_tags={"pv_dead": None},
    ))
    blob = py_storage.blob_path(p, digest)
    svc._pending_commit_assets.add("asset_p")  # touch #8
    removed1 = svc.purge_trashed()
    after_first = {
        "removed": removed1,
        "blob_survives_shared": blob.exists(),
        "asset_b1_alive": any(a.id == "asset_b1" for a in svc.document.assets),
        "zombie_gone": not any(a.id == "asset_z" for a in svc.document.assets),
        "pending_protected": any(a.id == "asset_p" for a in svc.document.assets),
        "mixed_untrashed_kept": next(
            (not a.trashed for a in svc.document.assets if a.id == "asset_m"),
            None),
        "dead_version_gone": not any(
            v.id == "pv_dead" for v in svc.document.versions),
        "live_version_kept": any(
            v.id == "pv_live" for v in svc.document.versions),
        "asset_tags_zombie_removed": "asset_z" not in svc.document.asset_tags,
    }
    # Last blob reference: trash the survivor, purge again → blob unlinked.
    svc.trash_version("pv_a", reason="last")
    removed2 = svc.purge_trashed()
    oracle["purge_refcount_blob"] = {
        "first": after_first,
        "second_removed": removed2,
        "blob_unlinked_at_last_ref": not blob.exists(),
        # pv_b + pv_dead + the trashed asset_m; the zombie (asset_b2, which
        # loses its only version) is removed but NOT counted.
        "zombie_not_counted": removed1 == 3,
    }

    # save-failure rollback: everything returns, payloads stay restorable.
    p2 = proj("tr5")
    svc2 = py_service_mod.DataCatalogService.open(p2, sweep_temp=False)
    doc2 = CatalogDocument()
    doc2.assets.append(asset("asset_rb", "Rollback"))
    doc2.versions.append(ver("rv_dead", "asset_rb", 1, trashed=True,
                             trashed_at=NOW,
                             path="tr5.artifacts/raw/asset_rb/rv_dead/x.bin"))
    doc2.tags.append(tag("rt1", "qc"))
    doc2.version_tags["rv_dead"] = ["rt1"]
    svc2.document = doc2
    svc2._invalidate_maps()
    svc2._save(DirtySet(
        assets={"asset_rb": None}, versions={"rv_dead": None}, tags={"rt1": None},
        version_tags={"rv_dead": None},
    ))
    versions_before = len(svc2.document.versions)
    svc2._index.apply_changes = lambda *a, **k: (_ for _ in ()).throw(
        RuntimeError("purge boom"))
    res = err_of(svc2.purge_trashed)
    del svc2._index.__dict__["apply_changes"]
    oracle["purge_save_failure_rollback"] = {
        "error": res["err"],
        "version_back": len(svc2.document.versions) == versions_before,
        "tag_map_back": "rv_dead" in svc2.document.version_tags,
        "asset_back": any(a.id == "asset_rb" for a in svc2.document.assets),
        "store_version_rows": count(svc2._index, "versions"),
    }
    svc.close()
    svc2.close()


