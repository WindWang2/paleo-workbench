def sec_query_surface(oracle: dict) -> None:
    doc = core_doc()
    p = proj("coreq")
    index = CatalogIndex(p)
    index.write_all(doc)
    service = py_service_mod.DataCatalogService.open(p, sweep_temp=False)

    matrix = [
        {"text": "ALPHA"}, {"text": "seismic a"},
        {"text": "grünfeld"}, {"text": "GRÜNFELD"},
        {"text": "m%m"}, {"text": "a_s"},
        {"stage": DataStage.RAW},
        {"tag": "QC"},
        {"tags": [" QC ", "", "zone"], "tag_op": "and"},
        {"tags": ["qc", "zone"], "tag_op": "or"},
        {"tags": ["qc", "nope"], "tag_op": "or"},
        {"type": "grid"},
        {"metadata": {"review_status": "approved"}},
        {"metadata": {"flag": True}},
        {"metadata": {"n": 5}},
        {"text": "Hidden"},
    ]
    cases = []
    for case in matrix:
        kw = dict(case)
        kw.setdefault("include_trashed", False)
        # Mirror queries.py's own pair stringification (str(v)) on the SQL
        # side so both paths see identical bind values.
        meta_pairs = [(str(k), str(v)) for k, v in (kw.get("metadata") or {}).items()]
        sql_rows = index.search_assets(
            text=kw.get("text"), stage=kw.get("stage"), tag=kw.get("tag"),
            tags=kw.get("tags"), tag_op=kw.get("tag_op", "and"),
            type=kw.get("type"), metadata=meta_pairs or None,
        )
        # Force the canonical document-scan path (conv-31 precedent).
        service._batch_depth = 1
        try:
            scan = py_queries.search_assets(service, **kw)
        finally:
            service._batch_depth = 0
        sql_unfiltered = sorted(r["id"] for r in sql_rows)
        # The db layer itself carries NO trashed predicate — the composed
        # path filters on the consumer side (queries.py:169-174). Compare
        # the filtered set against the scan; freeze the raw set separately.
        sql_ids = sorted(
            r["id"] for r in sql_rows
            if kw["include_trashed"] or not r["trashed"]
        )
        scan_ids = sorted(a.id for a in scan)
        cases.append({"case": {k: str(v) for k, v in case.items()},
                      "sql": sql_ids, "sql_unfiltered": sql_unfiltered,
                      "scan": scan_ids, "equal": sql_ids == scan_ids})
    # include_trashed variant on one text query.
    service._batch_depth = 1
    try:
        scan_tr = py_queries.search_assets(service, text="Hidden",
                                            include_trashed=True)
    finally:
        service._batch_depth = 0
    sql_tr_rows = index.search_assets(text="Hidden")
    sql_tr = sorted(r["id"] for r in sql_tr_rows)
    tr_ids = sorted(a.id for a in scan_tr)
    cases.append({"case": {"text": "Hidden", "include_trashed": "True"},
                  "sql": sql_tr, "sql_unfiltered": sql_tr,
                  "scan": tr_ids, "equal": sql_tr == tr_ids})
    # db-layer metadata normalization with a RAW bool (metadata_search_value
    # True → "1"): matches json_extract's CAST — no scan counterpart because
    # queries.py stringifies the pair to "True" before either path sees it.
    cases.append({
        "case": {"db_layer": "metadata flag raw True"},
        "sql": sorted(r["id"] for r in index.search_assets(
            metadata=[("flag", True)])),
        "sql_unfiltered": None, "scan": None, "equal": None,
    })
    oracle["db_search_dual_path"] = cases

    # Aggregates (db.py:2992-3042): stages joined on current_version_id,
    # types, tag display fallback ("" → name), review falsy skipped.
    agg_live = index.catalog_aggregates()
    agg_all = index.catalog_aggregates(include_trashed=True)
    oracle["db_aggregates"] = {"live": agg_live, "all": agg_all}

    # list_versions orders by version_number (db.py:3044) while the lazy
    # per-asset read keeps rowid/document order — pinned side by side.
    oracle["db_list_versions_order"] = {
        "sql_by_number": [r["id"] for r in index.list_versions("asset_a")],
        "lazy_by_rowid": [v.id for v in
                          index.list_version_models_for_asset("asset_a")],
        "service_sorted": [v.id for v in service.list_versions("asset_a")],
    }
    oracle["db_lineage_edges"] = {
        "ver_a2": index.lineage_edges("ver_a2"),
        "ver_a1": index.lineage_edges("ver_a1"),
    }
    oracle["db_for_tag_normalization"] = {
        "assets_qc_space": index.assets_for_tag(" QC "),
        "assets_qc_case": index.assets_for_tag("QC"),
        "versions_ZONE": index.versions_for_tag("ZONE"),
        "assets_unknown": index.assets_for_tag("nope"),
    }
    service.close()


