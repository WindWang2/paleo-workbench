def sec_db_channel(oracle: dict) -> None:
    # DirtySet semantics — db.py:756-829 (mark idempotent + position stable,
    # merge = self-first first-seen order, is_empty).
    d = DirtySet()
    d.mark_assets("a2")
    d.mark_assets("a1")
    d.mark_assets("a2")  # re-mark keeps first position
    d2 = DirtySet()
    d2.mark_assets("a1")
    d2.mark_assets("a3")
    d.merge(d2)
    d.mark_versions("v1")
    oracle["db_dirty_set"] = {
        "assets_order": list(d.assets),
        "versions_order": list(d.versions),
        "is_empty_while_marked": d.is_empty(),
    }
    d3 = DirtySet()
    oracle["db_dirty_set"]["empty_then"] = d3.is_empty()
    d3.mark_asset_tags("owner1")
    oracle["db_dirty_set"]["empty_after_tag_owner"] = d3.is_empty()

    base = CatalogDocument(catalog_revision=5)
    base.assets.extend([asset("d1", "Dee"), asset("a1", "Ay")])  # rowid order d1,a1
    base.assets[0].current_version_id = None
    base.versions.append(ver("v1", "d1", 1))
    p = proj("dbx")
    index = CatalogIndex(p)
    index.write_all(base)
    oracle["db_write_all_baseline"] = {
        "revision": index.revision(),
        "sync_state": sync_state(index),
        "assets_rowid_order": [
            r["id"] for r in rows(index, "SELECT id FROM assets ORDER BY rowid")
        ],
    }

    # CAS conflict inside the transaction (db.py:2036-2051) — the "保存"
    # message variant, zero write amplification.
    doc2 = base.model_copy(deep=True)
    doc2.catalog_revision = 6
    doc2.assets[1].name = "Aychanged"
    dirty = DirtySet(assets={"a1": None})
    raw_exec(p, "UPDATE sync_state SET value = '9' WHERE key = 'catalog_revision'")
    res = err_of(index.apply_changes, doc2, dirty, expected_revision=5)
    oracle["db_apply_cas_apply_variant"] = {
        "error": res["err"],
        "error_type": res["type"],
        "revision_after": index.revision(),
        "assets_rows": count(index, "assets"),
        "asset_name_unchanged": index.open().execute(
            "SELECT name FROM assets WHERE id = 'a1'").fetchone()[0],
    }
    raw_exec(p, "UPDATE sync_state SET value = '5' WHERE key = 'catalog_revision'")
    # expected_revision=0 while the key is missing entirely (db.py:2046).
    p0 = proj("dbx0")
    ix0 = CatalogIndex(p0)
    ix0.write_all(base)
    raw_exec(p0, "DELETE FROM sync_state WHERE key = 'catalog_revision'")
    res0 = err_of(ix0.apply_changes, base, DirtySet(), expected_revision=0)
    oracle["db_apply_cas_missing_key"] = {
        "error": res0["err"], "error_type": res0["type"],
    }

    # Successful apply: three-key stamp carries DOCUMENT-carried values
    # (db.py:2163-2170) — catalog_revision is the doc's, index layout is 5.
    doc3 = base.model_copy(deep=True)
    doc3.catalog_revision = 6
    doc3.assets[1].name = "Aychanged"
    doc3.versions.append(ver("v2", "a1", 1, stage=DataStage.DERIVED))
    index.apply_changes(
        doc3,
        DirtySet(assets={"a1": None}, versions={"v2": None}),
        expected_revision=5,
    )
    oracle["db_apply_success_stamp"] = {
        "sync_state": sync_state(index),
        "revision": index.revision(),
        "new_version_row": index.open().execute(
            "SELECT id, asset_id, stage FROM versions WHERE id = 'v2'"
        ).fetchone() and True,
    }

    # rowid preservation (db.py:2001-2026): existing rows keep rowid order,
    # new ids append in mark order — [d1, a1] + marks (a1, b, c, d1) →
    # [d1, a1, b, c].
    p1 = proj("dbx1")
    ix1 = CatalogIndex(p1)
    ix1.write_all(base)
    doc4 = base.model_copy(deep=True)
    doc4.assets.extend([asset("b1", "Bee"), asset("c1", "Cee")])
    marks = DirtySet(assets={"a1": None})
    marks.mark_assets("b1")
    marks.mark_assets("c1")
    marks.mark_assets("d1")
    ix1.apply_changes(doc4, marks)
    oracle["db_apply_rowid_order"] = {
        "order": [r["id"] for r in rows(ix1, "SELECT id FROM assets ORDER BY rowid")]
    }


def sec_db_cascade(oracle: dict) -> None:
    # Deletion cascade matrix (db.py:2052-2162 + keep-rule helpers
    # 2179-2311): asset delete cascades asset_tags only; tag delete cascades
    # both association tables; version delete keeps run-covered lineage edges
    # and drops uncovered ones; run delete keeps version-owned edges;
    # derived collections (members/ports) clear even when the new set is
    # empty.
    doc = CatalogDocument(catalog_revision=2)
    doc.assets.extend([
        asset("as_del", "Deleted"),
        asset("as_keep", "Kept"),
        asset("as_t", "Tagged"),
    ])
    doc.versions.extend([
        ver("vd1", "as_del", 1), ver("vd2", "as_del", 2),
        ver("vk_parent", "as_keep", 1),
        ver("vk_child", "as_keep", 2, stage=DataStage.DERIVED,
            parent_version_ids=["vk_parent"]),
        ver("vf_parent", "as_keep", 3),
        ver("vf_child", "as_keep", 4, stage=DataStage.DERIVED,
            parent_version_ids=["vf_parent"]),
        ver("v_rv_in", "as_keep", 5),
        ver("v_rv_out", "as_keep", 6, stage=DataStage.DERIVED,
            parent_version_ids=["v_rv_in"]),
        ver("v_rn_in", "as_keep", 7),
        ver("v_rn_out", "as_keep", 8, stage=DataStage.DERIVED),
        ver("v_bundle", "as_t", 1, stage=DataStage.INTERMEDIATE),
    ])
    doc.runs.extend([
        run("r_cover", inputs=["vk_parent"], outputs=["vk_child"]),
        run("r_rv", inputs=["v_rv_in"], outputs=["v_rv_out"]),
        run("r_rn", inputs=["v_rn_in"], outputs=["v_rn_out"]),
        run("r_ports", inputs=["v_bundle"], outputs=[],
            input_ports=[RunPort(role="in", version_id="v_bundle", ordinal=0)],
            output_ports=[RunPort(role="out", version_id="v_bundle", ordinal=0)]),
    ])
    doc.tags.append(tag("tg1", "qc"))
    doc.asset_tags.update({"as_del": ["tg1"], "as_t": ["tg1"]})
    doc.version_tags.update({"vd1": ["tg1"]})
    doc.versions[10].members = [
        VersionMember(name="m1", rel_path="m1.bin", ordinal=0, sha256="aa" * 32,
                      size_bytes=1),
        VersionMember(name="m2", rel_path="m2.bin", ordinal=1, sha256="bb" * 32,
                      size_bytes=2),
    ]
    p = proj("dbc")
    index = CatalogIndex(p)
    index.write_all(doc)

    doc2 = doc.model_copy(deep=True)
    doc2.catalog_revision = 3
    # as_del removed but its versions STAY (document is the authority; the
    # cascade is driven by the versions' own dirty marks).
    doc2.assets = [a for a in doc2.assets if a.id != "as_del"]
    doc2.tags = []
    doc2.versions = [
        v for v in doc2.versions
        if v.id not in ("vk_child", "vf_child")
    ]
    doc2.runs = [r for r in doc2.runs if r.id not in ("r_rv", "r_rn")]
    doc2.asset_tags = {"as_del": []}
    doc2.asset_tags.pop("as_del")
    doc2.asset_tags["as_t"] = []
    doc2.version_tags = {}
    bundle = next(v for v in doc2.versions if v.id == "v_bundle")
    bundle.members = []
    ports_run = next(r for r in doc2.runs if r.id == "r_ports")
    ports_run.input_ports = []
    ports_run.output_ports = []
    dirty = DirtySet(
        assets={"as_del": None}, tags={"tg1": None},
        versions={"vk_child": None, "vf_child": None, "v_bundle": None},
        runs={"r_rv": None, "r_rn": None, "r_ports": None},
        asset_tags={"as_t": None}, version_tags={"vd1": None},
    )
    index.apply_changes(doc2, dirty)
    conn = index.open()
    oracle["db_apply_delete_cascade"] = {
        "assets": [r["id"] for r in rows(index, "SELECT id FROM assets ORDER BY rowid")],
        # versions of the deleted asset survive (no FK cascade):
        "versions_of_deleted_asset": count(index, "versions", "asset_id = 'as_del'"),
        "tags_rows": count(index, "tags"),
        "asset_tags_rows": count(index, "asset_tags"),
        "version_tags_rows": count(index, "version_tags"),
        "lineage_edges": sorted(
            f"{a}->{b}" for a, b in conn.execute(
                "SELECT parent_version_id, child_version_id FROM lineage")
        ),
        # run_inputs/run_outputs survive the version delete (owned by run):
        "cover_run_io_after_version_delete": count(
            index, "run_inputs", "run_id = 'r_cover'"),
        "run_io_after_run_delete": count(index, "run_inputs", "run_id = 'r_rv'"),
        "members_cleared": count(index, "version_members", "version_id = 'v_bundle'"),
        "ports_cleared": count(index, "run_ports", "run_id = 'r_ports'"),
        "revision": index.revision(),
    }


def sec_db_reconcile(oracle: dict) -> None:
    # reconcile diff sets (db.py:2313-2475): row-changed / doc-only /
    # db-only across the six tables, association-map drift, run io drift,
    # ports/members drift — then equivalence with a full rebuild.
    doc = CatalogDocument(catalog_revision=4)
    doc.assets.extend([asset("ra1", "One"), asset("ra2", "Two")])
    doc.versions.extend([
        ver("rv1", "ra1", 1), ver("rv2", "ra1", 2),
        ver("rv_gone", "ra2", 1),
        ver("rv_bundle", "ra1", 3, stage=DataStage.INTERMEDIATE),
    ])
    doc.runs.append(run("rr1", inputs=["rv1"], outputs=["rv2"],
                        input_ports=[RunPort(role="in", version_id="rv1")]))
    doc.tags.append(tag("rt1", "qc"))
    doc.asset_tags["ra1"] = ["rt1"]
    doc.version_tags["rv2"] = ["rt1"]
    doc.versions[3].members = [
        VersionMember(name="m", rel_path="m.bin", ordinal=0, sha256="cc" * 32,
                      size_bytes=9)]
    p = proj("dbr")
    index = CatalogIndex(p)
    index.write_all(doc)

    doc2 = doc.model_copy(deep=True)
    doc2.catalog_revision = 5
    doc2.assets[0].name = "One-changed"        # row-changed
    doc2.versions.append(ver("rv_new", "ra1", 4))  # doc-only
    doc2.versions = [v for v in doc2.versions if v.id != "rv_gone"]  # db-only
    doc2.models.append(Model(id="rm1", model_id="m-logical", model_name="M",
                             created_at=TS))
    doc2.model_versions.append(ModelVersion(
        id="rmv1", model_id="m-logical", status="demo", created_at=TS))
    doc2.asset_tags["ra1"] = []                 # association drift
    doc2.version_tags["rv2"] = []
    doc2.runs[0].output_version_ids = []        # run io drift
    doc2.runs[0].input_ports = []               # ports drift
    doc2.versions[3].members = []               # members drift
    index.reconcile(doc2)
    after = dump(index)

    p2 = proj("dbr2")
    index2 = CatalogIndex(p2)
    index2.write_all(doc2)
    rebuilt = dump(index2)
    oracle["db_reconcile_drift"] = {
        "after_reconcile": after,
        "after_rebuild": rebuilt,
        "equal": after == rebuilt,
        # KNOWN divergence, frozen as-is: apply_changes rewrites a dirty
        # run's run_inputs/run_outputs BEFORE _reconcile_run_edges reads
        # its "old" pairs (db.py:2079-2096), so a SHRINKING run's derived
        # lineage edge survives reconcile while a full rebuild drops it.
        # Entity rows are identical; only the lineage table differs.
        "lineage_known_divergence": after.get("lineage") != rebuilt.get(
            "lineage"),
        "revision": index.revision(),
    }

    # Empty diff: reconcile still refreshes the three-key stamp under the
    # same CAS contract (db.py:2437-2474).
    doc3 = doc2.model_copy(deep=True)
    doc3.catalog_revision = 6
    index.reconcile(doc3)
    oracle["db_reconcile_empty_stamp"] = {
        "sync_state": sync_state(index),
        "is_fresh": index.is_fresh(doc3),
    }
    # The "同步" message variant of the in-transaction CAS (db.py:2454-2458).
    raw_exec(p, "UPDATE sync_state SET value = '40' WHERE key = 'catalog_revision'")
    res = err_of(index.reconcile, doc3, expected_revision=6)
    oracle["db_reconcile_cas_sync_variant"] = {
        "error": res["err"], "error_type": res["type"],
    }


def sec_db_rebuild_equiv(oracle: dict) -> None:
    # rebuild == apply equivalence (db.py I3): three incremental applies then
    # a comparison against a fresh write_all of the same document.
    doc = CatalogDocument(catalog_revision=1)
    doc.assets.append(asset("ea1", "Ee"))
    doc.versions.append(ver("ev1", "ea1", 1))
    p = proj("dbe")
    index = CatalogIndex(p)
    index.write_all(doc)
    for step in range(3):
        doc.catalog_revision += 1
        doc.assets[0].name = f"Ee{step}"
        doc.versions.append(ver(f"ev{step + 2}", "ea1", step + 2,
                                stage=DataStage.DERIVED))
        index.apply_changes(doc, DirtySet(
            assets={"ea1": None}, versions={f"ev{step + 2}": None}))
    p2 = proj("dbe2")
    index2 = CatalogIndex(p2)
    index2.write_all(doc)
    a, b = dump(index), dump(index2)
    oracle["db_rebuild_equivalence"] = {"equal": a == b, "dump": a}


