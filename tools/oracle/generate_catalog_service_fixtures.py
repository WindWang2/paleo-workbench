        if isinstance(eager_value, list):
            ok = [J(x) if hasattr(x, "model_dump") else x for x in lazy] == \
                 [J(x) if hasattr(x, "model_dump") else x for x in eager_value]
        elif hasattr(eager_value, "model_dump"):
            ok = J(lazy) == J(eager_value)
        else:
            ok = lazy == eager_value
        frozen = [J(x) for x in lazy] if isinstance(lazy, list) else (
            J(lazy) if hasattr(lazy, "model_dump") else lazy)
