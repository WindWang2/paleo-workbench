def sec_manifest(oracle: dict) -> None:
    digest = lambda p: sha_bytes(Path(p).read_bytes())

    p = proj("mf1")
    st = CatalogStore(p)
    doc1, doc2 = mf_doc(1), mf_doc(2, "Second")
    st.save(doc1)
    loaded = st.load()
    oracle["manifest_load_ok"] = {
        "revision": loaded.catalog_revision,
        "asset_names": [a.name for a in loaded.assets],
        "canonical_exists": py_store_path(p).exists(),
    }
    first_digest = digest(py_store_path(p))
    st.save(doc2)  # rotation: bak now holds revision 1
    oracle["manifest_save_rotation"] = {
        "canonical_is_rev2": st.load().catalog_revision == 2,
        "bak_matches_previous": digest(py_store_bak(p)) == first_digest,
    }
    # unchanged-skip (#1183): same instance, same payload, untouched mtime.
    mtime_before = py_store_path(p).stat().st_mtime_ns
    bak_mtime_before = py_store_bak(p).stat().st_mtime_ns
    st.save(doc2)
    oracle["manifest_save_unchanged_skip"] = {
        "canonical_mtime_unchanged":
            py_store_path(p).stat().st_mtime_ns == mtime_before,
        "bak_mtime_unchanged": py_store_bak(p).stat().st_mtime_ns == bak_mtime_before,
    }
    # External modification defeats the mtime guard → rewrite happens.
    import os

    old = py_store_path(p).stat().st_mtime_ns
    os.utime(py_store_path(p), (old + 10, old + 10))
    st.save(doc2)
    oracle["manifest_save_unchanged_skip"]["external_edit_rewrites"] = (
        py_store_path(p).stat().st_mtime_ns != old
    )

    # First-save backup seeding (#372/C14): a fresh project's first save
    # leaves a bak holding the SAME revision payload.
    p2 = proj("mf2")
    st2 = CatalogStore(p2)
    st2.save(doc1)
    oracle["manifest_save_seed"] = {
        "bak_exists": py_store_bak(p2).exists(),
        "digests_equal": digest(py_store_path(p2)) == digest(py_store_bak(p2)),
    }

    # L3 (canonical missing, bak present): re-promotion (store.py:131-154).
    p3 = proj("mf3")
    st3 = CatalogStore(p3)
    st3.save(doc1)
    st3.save(doc2)
    py_store_path(p3).unlink()
    loaded3 = st3.load()
    oracle["manifest_load_bak_repromote"] = {
        "revision": loaded3.catalog_revision,
        "bak_consumed": not py_store_bak(p3).exists(),
        "canonical_back": py_store_path(p3).exists(),
    }
    # L3' (canonical corrupt, bak readable): same promotion, corrupt bytes
    # are replaced by the re-promoted bak.
    p4 = proj("mf4")
    st4 = CatalogStore(p4)
    st4.save(doc1)
    st4.save(doc2)
    py_store_path(p4).write_text("{corrupt", encoding="utf-8")
    loaded4 = st4.load()
    oracle["manifest_load_corrupt_isolated"] = {
        "revision": loaded4.catalog_revision,
        "bak_consumed": not py_store_bak(p4).exists(),
        "canonical_back": py_store_path(p4).exists(),
    }

    # L2 (corrupt canonical, no bak): verbatim message + isolation
    # (store.py:125-130, 48-63).
    p5 = proj("mf5")
    st5 = CatalogStore(p5)
    py_store_path(p5).parent.mkdir(parents=True, exist_ok=True)
    py_store_path(p5).write_text("not json at all", encoding="utf-8")
    res5 = err_of(st5.load)
    isolated5 = list(py_store_path(p5).parent.glob("catalog.json.corrupt-*"))
    oracle["manifest_load_no_backup_error"] = {
        "error": res5["err"], "type": res5["type"],
        "isolated_count": len(isolated5),
    }
    # L4 (both corrupt): double isolation + the audit-#848 message.
    p6 = proj("mf6")
    st6 = CatalogStore(p6)
    py_store_path(p6).parent.mkdir(parents=True, exist_ok=True)
    py_store_path(p6).write_text("{nope", encoding="utf-8")
    py_store_bak(p6).write_text("[nope", encoding="utf-8")
    res6 = err_of(st6.load)
    isolated6 = list(py_store_path(p6).parent.glob("catalog.json.corrupt-*"))
    oracle["manifest_load_both_corrupt_error"] = {
        "error": res6["err"], "type": res6["type"],
        "isolated_count": len(isolated6),
    }
    # L5 (both absent): empty document, revision 0.
    p7 = proj("mf7")
    loaded7 = CatalogStore(p7).load()
    oracle["manifest_load_absent"] = {
        "revision": loaded7.catalog_revision,
        "empty": not loaded7.assets and not loaded7.versions,
    }


