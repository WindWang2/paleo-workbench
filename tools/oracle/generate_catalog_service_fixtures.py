def sec_promote_version(oracle: dict) -> None:
    p = proj("pv")
    svc = py_service_mod.DataCatalogService.open(p, sweep_temp=False)
    content = b"promote-me"
    src = TMP / "pv" / "in.dat"
    src.parent.mkdir(parents=True, exist_ok=True)
    src.write_bytes(content)
    v1 = svc.register_result_asset(
        name="Promotable", type="seismic", format="sgy", asset_metadata={},
        source_path=src, stage=DataStage.RAW)
    src2 = TMP / "pv" / "v2.dat"
    src2.write_bytes(b"promote-me-2")
    v2 = svc.register_version(v1.asset_id, src2, DataStage.DERIVED)
    numbers_before = [
        v.version_number for v in svc.list_versions(v1.asset_id)]
    promoted = svc.promote_version(v2.id, reviewed_by="kevin")
    run = next(r for r in svc.document.runs if r.operation == "promote")
    oracle["promote_version_shape"] = {
        "numbers_before": numbers_before,
        "new_number": promoted.version_number,
        "run": {
            "operation": run.operation,
            "inputs": run.input_version_ids,
            "outputs": run.output_version_ids,
            "parameters": run.parameters,
        },
        "parents": promoted.parent_version_ids,
        "metadata": promoted.metadata,
        "stage": promoted.stage.value,
        "sha_copied": promoted.sha256 == sha_bytes(b"promote-me-2"),
        "source_payload_intact": src2.exists(),
        "current_advanced": svc.get_asset(promoted.asset_id)
        .current_version_id == promoted.id,
        "path": promoted.path,
        "numbers_after": [
            v.version_number for v in svc.list_versions(v1.asset_id)],
    }
    # A second promote re-allocates inside the lock: numbers stay sequential.
    promoted2 = svc.promote_version(promoted.id)
    oracle["promote_version_realloc"] = {
        "numbers": [v.version_number for v in svc.list_versions(v1.asset_id)],
        "distinct": promoted2.version_number == promoted.version_number + 1,
    }
    svc.close()


