#!/usr/bin/env python3
"""Emit libs/domain/src/lower_table.inc — the str.lower() mapping table.

Same generation contract as tools/oracle/generate_interchange_fixtures.py:
the table is produced by the REAL Python semantics (str.lower), never
hand-written, so C++ text normalization cannot drift from the product's
Python reference (#1391: ASCII-only folds silently zero non-ASCII search
results for accented Latin / Cyrillic / Greek asset names).

Run:  python3 tools/oracle/generate_domain_lower_table.py
Out:  libs/domain/src/lower_table.inc
"""
from __future__ import annotations

import unicodedata
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
TABLE = REPO_ROOT / "libs" / "domain" / "src" / "lower_table.inc"


def _escape(text: str) -> str:
    return "".join(
        f"\\x{byte:02x}"
        if byte < 0x20 or byte >= 0x7F or byte in (0x22, 0x5C)
        else chr(byte)
        for byte in text.encode("utf-8")
    )


def emit() -> None:
    # Every code point whose str.lower()/str.casefold() differs from itself.
    # Multi-codepoint results (e.g. U+0130 -> "i̇", U+00DF -> "ss") are kept
    # whole — Python semantics, not approximations.
    def collect(fn) -> list[tuple[int, str]]:
        return [
            (cp, folded)
            for cp in range(0x110000)
            if (folded := fn(chr(cp))) != chr(cp)
        ]

    lowers = collect(lambda ch: ch.lower())
    folds = collect(lambda ch: ch.casefold())

    lines = [
        "// Generated by tools/oracle/generate_domain_lower_table.py — DO NOT EDIT.",
        f"// Source: system python3 str.lower()/str.casefold() "
        f"(Unicode {unicodedata.unidata_version}).",
        "#pragma once",
        "#include <cstdint>",
        "",
        "namespace pwb::domain::lower_table {",
        "",
        "struct LowerEntry { std::uint32_t cp; const char* folded; };",
        "inline const LowerEntry kLower[] = {",
    ]
    lines += [
        f'    {{{cp:#x},"{_escape(folded)}"}},' for cp, folded in lowers
    ]
    lines += [
        "};",
        "inline const LowerEntry kCasefold[] = {",
    ]
    lines += [
        f'    {{{cp:#x},"{_escape(folded)}"}},' for cp, folded in folds
    ]
    lines += [
        "};",
        "",
        "}  // namespace pwb::domain::lower_table",
        "",
    ]
    TABLE.write_text("\n".join(lines), encoding="utf-8")
    print(
        f"lower_table.inc: {len(lowers)} str.lower + {len(folds)} str.casefold"
        f" entries -> {TABLE}"
    )


if __name__ == "__main__":
    emit()
