def _read(fn, tmp, payload):
    suffix = {"read_flac3d_grid": ".f3grid", "read_abaqus_inp": ".inp",
              "read_obj": ".obj", "read_stl": ".stl",
              "read_vtp": ".vtp"}[fn]
    p = tmp / ("case" + suffix)
    if isinstance(payload, (bytes, bytearray)):
        p.write_bytes(payload)
    else:
        p.write_text(payload, encoding="utf-8")
    fmap = {"read_flac3d_grid": exporters.read_flac3d_grid,
            "read_abaqus_inp": exporters.read_abaqus_inp,
            "read_obj": exporters.read_obj,
            "read_stl": exporters.read_stl,
            "read_vtp": exporters.read_vtp}
    out = fmap[fn](p)
    # zones/elements are tuples of ints — J() handles; nodes arrays too.
    return out


