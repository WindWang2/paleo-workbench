CASES = []


def case(cid, fn, input_, fn_, *, fix=None):
    try:
        result = fn_()
        entry = {"id": cid, "fn": fn, "input": J(input_),
                 "expect": {"result": J(result)}}
    except Exception as exc:  # noqa: BLE001 — class names are the oracle
        entry = {"id": cid, "fn": fn, "input": J(input_),
                 "expect": {"raises": type(exc).__name__,
                            "message": str(exc)}}
    if fix:
        fix(entry)
    CASES.append(entry)


