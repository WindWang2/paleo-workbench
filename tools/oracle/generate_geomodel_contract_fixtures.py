def construct(spec):
    kind = spec["kind"]
    kw = common_kwargs(spec)
    if kind == "well":
        return domain.WellTrajectory(
            stations=arr(spec.get("stations", [])),
            representation=spec.get("representation", "measured"),
            z_unit=spec.get("z_unit"),
            well_asset_id=spec.get("well_asset_id", ""),
            formation_tops=tuple(
                (str(t[0]), float(t[1])) for t in spec.get("formation_tops", ())
            ),
            **kw,
        )
    if kind == "horizon":
        return domain.HorizonSurface(
            z_grid=arr(spec.get("z_grid", [])),
            origin=tuple(spec.get("origin", (0.0, 0.0))),
            spacing=tuple(spec.get("spacing", (1.0, 1.0))),
            grid_crs=spec.get("grid_crs", ""),
            horizon_asset_id=spec.get("horizon_asset_id", ""),
            confidence=arr(spec["confidence"]) if "confidence" in spec else None,
            attributes=tuple(
                (n, arr(a)) for n, a in spec.get("attributes", ())
            ),
            **kw,
        )
    if kind == "fault":
        zd = spec.get("z_extent")
        sd = spec.get("strike_dip")
        return domain.FaultSurface(
            verts=arr(spec.get("verts", [])),
            faces=iarr(spec.get("faces", [])),
            representation=spec.get("representation", "triangulated_3d"),
            trace_xy=arr(spec["trace_xy"]) if "trace_xy" in spec else None,
            z_extent=tuple(zd) if zd is not None else None,
            throw_m=spec.get("throw_m"),
            strike_dip=tuple(sd) if sd is not None else None,
            fault_asset_id=spec.get("fault_asset_id", ""),
            intersects_horizons=tuple(spec.get("intersects_horizons", ())),
            **kw,
        )
    if kind == "volume":
        return domain.StratigraphicVolume(
            verts=arr(spec.get("verts", [])),
            faces=iarr(spec.get("faces", [])),
            top_id=spec.get("top_id", ""),
            base_id=spec.get("base_id", ""),
            boundary=arr(spec["boundary"]) if "boundary" in spec else None,
            formation=spec.get("formation", ""),
            facies=iarr(spec["facies"]) if "facies" in spec else None,
            properties=tuple(
                (n, arr(a)) for n, a in spec.get("properties", ())
            ),
            cell_mesh=spec.get("cell_mesh"),
            quality=dict(spec.get("quality", {})),
            **kw,
        )
    if kind == "tunnel":
        return domain.TunnelSection(
            path=arr(spec.get("path", [])),
            radius=spec.get("radius", 3.0),
            **kw,
        )
    if kind == "measure":
        return domain.MeasurementRecord(
            measurement_kind=spec.get("measurement_kind", "distance"),
            points=arr(spec.get("points", [])),
            result=spec.get("result"),
            extra=dict(spec.get("extra", {})),
            **kw,
        )
    raise AssertionError(f"unknown kind {kind}")


def mutate(obj, spec):
    """Post-construction mutations (frozen-by-convention bypass) — the QC
    crash/report paths the constructor guards against."""
    for m in spec.get("_mutate", ()):
        target, idx, val = m["field"], m.get("index"), m.get("value")
        a = getattr(obj, target)
        v = math.nan if val is None else val
        if target in ("stations", "verts", "path", "points", "z_grid",
                      "confidence"):
            if isinstance(idx, int):
                a.flat[idx] = v
            else:
                a[tuple(idx)] = v
        elif target == "faces":
            if isinstance(idx, int):
                a.flat[idx] = int(v)
            else:
                a[tuple(idx)] = int(v)
        else:
            raise AssertionError(f"mutate target {target}")
    return obj


def spec_of(obj):
    """domain object -> constructor spec (arrays -> JSON lists)."""
    kind = obj.kind()
    s = {
        "kind": kind,
        "object_id": obj.object_id,
        "name": obj.name,
        "crs": obj.crs,
        "vertical_domain": obj.vertical_domain,
        "unit": obj.unit,
        "version": obj.version,
        "provenance": J(obj.provenance.to_meta()),
    }
    if kind == "well":
        s.update(stations=J(obj.stations), representation=obj.representation,
                 z_unit=obj.z_unit, well_asset_id=obj.well_asset_id,
                 formation_tops=[list(t) for t in obj.formation_tops])
    elif kind == "horizon":
        s.update(z_grid=J(obj.z_grid), origin=list(obj.origin),
                 spacing=list(obj.spacing), grid_crs=obj.grid_crs,
                 horizon_asset_id=obj.horizon_asset_id,
                 confidence=J(obj.confidence) if obj.confidence is not None else None,
                 attributes=[[n, J(a)] for n, a in obj.attributes])
    elif kind == "fault":
        s.update(verts=J(obj.verts), faces=J(obj.faces),
                 representation=obj.representation,
                 z_extent=list(obj.z_extent) if obj.z_extent else None,
                 throw_m=obj.throw_m,
                 strike_dip=list(obj.strike_dip) if obj.strike_dip else None,
                 fault_asset_id=obj.fault_asset_id,
                 intersects_horizons=list(obj.intersects_horizons))
    elif kind == "volume":
        s.update(verts=J(obj.verts), faces=J(obj.faces),
                 top_id=obj.top_id, base_id=obj.base_id,
                 boundary=J(obj.boundary) if obj.boundary is not None else None,
                 formation=obj.formation,
                 facies=J(obj.facies) if obj.facies is not None else None,
                 properties=[[n, J(a)] for n, a in obj.properties],
                 cell_mesh=obj.cell_mesh,
                 quality=dict(obj.quality))
    elif kind == "tunnel":
        s.update(path=J(obj.path), radius=obj.radius)
    elif kind == "measure":
        s.update(measurement_kind=obj.measurement_kind, points=J(obj.points),
                 result=obj.result, extra=dict(obj.extra))
    return s


