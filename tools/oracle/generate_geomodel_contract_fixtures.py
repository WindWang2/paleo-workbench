def J(x):
    if isinstance(x, np.ndarray):
        return J(x.tolist())
    if isinstance(x, np.generic):
        return J(x.item())
    if isinstance(x, float):
        if math.isnan(x):
            return None
        if x == math.inf:
            return "inf"
        if x == -math.inf:
            return "-inf"
        return x
    if isinstance(x, dict):
        return {str(k): J(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [J(v) for v in x]
    if isinstance(x, (bytes, bytearray)):
        return {"b64": base64.b64encode(bytes(x)).decode("ascii")}
    if isinstance(x, Path):
        return str(x)
    return x


def arr(x, dtype=np.float64):
    """JSON list -> ndarray; null inside arrays becomes NaN."""
    if x is None:
        return None
    def conv(v):
        return math.nan if v is None else v
    def deep(v):
        if isinstance(v, list):
            return [deep(e) for e in v]
        return conv(v)
    return np.asarray(deep(x), dtype=dtype)


def iarr(x):
    if x is None:
        return None
    return np.asarray(x, dtype=np.int64)


def opt(x):
    """spec value: explicit null -> None (Python None), missing handled by get()."""
    return x


