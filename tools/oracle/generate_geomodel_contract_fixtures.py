def write_lower_map():
    """str.lower() table: every code point whose .lower() differs, emitted
    as (cp, utf8-string) pairs. Generated by the same Python that freezes
    the oracle (str.lower != str.casefold, e.g. ß/ﬀ)."""
    rows = []
    for cp in range(0x110000):
        lo = chr(cp).lower()
        if lo != chr(cp):
            esc = "".join(f"\\x{c:02x}" for c in lo.encode("utf-8"))
            rows.append(f'    {{0x{cp:05X}u, "{esc}"}},')
    body = "// generated by generate_geomodel_contract_fixtures.py — str.lower()\n"
    body += "// map for code points where lower(cp) != cp\n"
    body += "\n".join(rows) + "\n"
    LOWER_INC.write_text(body, encoding="utf-8")
    return len(rows)

