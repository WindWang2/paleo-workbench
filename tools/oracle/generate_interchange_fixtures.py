def section_within_root() -> list[dict]:
    """Layouts replayed by both sides in their own temp dirs."""
    scenarios = [
        {"id": "inside-existing",
         "layout": {"dirs": ["pkg/sub"], "files": ["pkg/sub/f.txt"], "symlinks": {}},
         "root": "pkg", "candidate": "pkg/sub/f.txt",
         "expect": "inside", "inside_rel": "sub/f.txt"},
        {"id": "inside-root-itself",
         "layout": {"dirs": ["pkg"], "files": [], "symlinks": {}},
         "root": "pkg", "candidate": "pkg",
         "expect": "inside", "inside_rel": "."},
        {"id": "inside-not-yet-written",
         "layout": {"dirs": ["pkg"], "files": [], "symlinks": {}},
         "root": "pkg", "candidate": "pkg/new.bin",
         "expect": "inside", "inside_rel": "new.bin"},
        {"id": "escape-sibling",
         "layout": {"dirs": ["pkg"], "files": ["outside.txt"], "symlinks": {}},
         "root": "pkg", "candidate": "outside.txt",
         "expect": "escape", "inside_rel": None},
        {"id": "symlink-file",
         "layout": {"dirs": ["pkg"], "files": ["outside.txt"],
                    "symlinks": {"pkg/link.txt": "../outside.txt"}},
         "root": "pkg", "candidate": "pkg/link.txt",
         "expect": "symlink", "inside_rel": None},
        {"id": "escape-through-dirlink",
         "layout": {"dirs": ["pkg", "outside"], "files": ["outside/x.txt"],
                    "symlinks": {"pkg/dirlink": "../outside"}},
         "root": "pkg", "candidate": "pkg/dirlink/x.txt",
         "expect": "escape", "inside_rel": None},
    ]
    checked = []
    work = Path(tempfile.mkdtemp(prefix="pwb-oracle-root-"))
    try:
        for scenario in scenarios:
            base = work / scenario["id"]
            base.mkdir()
            for rel in scenario["layout"]["dirs"]:
                (base / rel).mkdir(parents=True, exist_ok=True)
            for rel in scenario["layout"]["files"]:
                (base / rel).write_text("x", encoding="utf-8")
            for link, target in scenario["layout"]["symlinks"].items():
                (base / link).symlink_to(target)
            outcome = {"inside": None, "symlink": None, "escape": None}
            prefix = ""
            try:
                resolved = ensure_within_root(base / scenario["root"],
                                              base / scenario["candidate"])
                outcome["inside"] = resolved.relative_to((base / scenario["root"]).resolve()).as_posix()
            except UnsafePathError as exc:
                message = str(exc)
                prefix = message.split(":", 1)[0]
                if message.startswith("symlink rejected"):
                    outcome["symlink"] = message
                elif message.startswith("path escapes package root"):
                    outcome["escape"] = message
                else:
                    raise AssertionError(f"unexpected message: {message}") from exc
            scenario["message_prefix"] = prefix
            expect = scenario["expect"]
            assert outcome[expect] is not None or expect == "inside", scenario
            if expect == "inside":
                assert outcome["inside"] == scenario["inside_rel"], scenario
            checked.append({**scenario, "observed_rel": outcome["inside"]})
    finally:
        shutil.rmtree(work, ignore_errors=True)
    return checked


