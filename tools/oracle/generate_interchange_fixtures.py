def emit_unicode_tables() -> None:
    decomps: list[tuple[int, tuple[int, ...]]] = []
    for cp in range(0x110000):
        if 0xAC00 <= cp <= 0xD7A3:  # Hangul syllables: algorithmic
            continue
        d = unicodedata.decomposition(chr(cp))
        if not d or d.startswith("<"):
            continue
        seq = tuple(int(part, 16) for part in d.split())
        decomps.append((cp, seq))

    compositions: list[tuple[int, int, int]] = []
    for cp, seq in decomps:
        if len(seq) != 2:
            continue  # singletons recompose to themselves; triples never compose
        composed = unicodedata.normalize("NFC", "".join(chr(c) for c in seq))
        if composed == chr(cp):
            compositions.append((seq[0], seq[1], cp))
    compositions.sort(key=lambda entry: (entry[0], entry[1]))

    ccc_pairs = [
        (cp, unicodedata.combining(chr(cp)))
        for cp in range(0x110000)
        if unicodedata.combining(chr(cp)) != 0
    ]
    ccc_ranges: list[tuple[int, int, int]] = []
    for cp, value in ccc_pairs:
        if ccc_ranges and ccc_ranges[-1][1] == cp - 1 and ccc_ranges[-1][2] == value:
            ccc_ranges[-1] = (ccc_ranges[-1][0], cp, value)
        else:
            ccc_ranges.append((cp, cp, value))

    folds: list[tuple[int, str]] = []
    for cp in range(0x110000):
        ch = chr(cp)
        folded = ch.casefold()
        if folded != ch:
            folds.append((cp, folded))

    lines = [
        "// Generated by tools/oracle/generate_interchange_fixtures.py — DO NOT EDIT.",
        f"// Source: system python3 unicodedata (Unicode {unicodedata.unidata_version})"
        " + str.casefold (full folding).",
        "#pragma once",
        "#include <cstdint>",
        "",
        "namespace pwb::interchange::unicode_tables {",
        "",
        "struct DecompEntry { std::uint32_t cp; std::uint8_t n; std::uint32_t seq[3]; };",
        f"inline const DecompEntry kCanonicalDecompositions[] = {{",
    ]
    for cp, seq in decomps:
        padded = list(seq) + [0] * (3 - len(seq))
        lines.append(
            "    {{{:#x},{},{{{},{},{}}}}},".format(cp, len(seq), *padded)
        )
    lines += [
        "};",
        "struct ComposeEntry { std::uint32_t a, b, cp; };",
        "inline const ComposeEntry kCanonicalCompositions[] = {",
    ]
    for a, b, cp in compositions:
        lines.append(f"    {{{a:#x},{b:#x},{cp:#x}}},")
    lines += [
        "};",
        "struct CccRange { std::uint32_t first, last; std::uint8_t ccc; };",
        "inline const CccRange kCccRanges[] = {",
    ]
    for first, last, value in ccc_ranges:
        lines.append(f"    {{{first:#x},{last:#x},{value}}},")
    lines += [
        "};",
        "struct FoldEntry { std::uint32_t cp; const char* folded; };",
        "inline const FoldEntry kCasefold[] = {",
    ]
    for cp, folded in folds:
        escaped = "".join(
            f"\\x{byte:02x}" if byte < 0x20 or byte >= 0x7F or byte in (0x22, 0x5C)
            else chr(byte)
            for byte in folded.encode("utf-8")
        )
        lines.append(f'    {{{cp:#x},"{escaped}"}},')
    lines += [
        "};",
        "",
        "}  // namespace pwb::interchange::unicode_tables",
        "",
    ]
    TABLES.parent.mkdir(parents=True, exist_ok=True)
    TABLES.write_text("\n".join(lines), encoding="utf-8")
    print(
        f"unicode_tables.inc: {len(decomps)} decomp, {len(compositions)} compose,"
        f" {len(ccc_ranges)} ccc ranges, {len(folds)} casefold entries"
    )


