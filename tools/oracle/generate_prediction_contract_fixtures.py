def _call(fn, *args, **kwargs):
    """Run fn -> {"result": ...} or {"raises": cls, "message": ...}."""
    try:
        return {"result": fn(*args, **kwargs)}
    except Exception as exc:  # noqa: BLE001
        return {"raises": exc.__class__.__name__, "message": str(exc)}


def _sub(value, prefix=None):
    """Replace ``$FX`` markers with the real fixture-files dir (call side)."""
    prefix = str(FILES) if prefix is None else prefix
    if isinstance(value, str):
        return value.replace(FX, prefix)
    if isinstance(value, list):
        return [_sub(v, prefix) for v in value]
    if isinstance(value, dict):
        return {k: _sub(v, prefix) for k, v in value.items()}
    return value


def _unsub(value):
    """Rewrite real fixture-dir paths back to ``$FX`` (expect side)."""
    prefix = str(FILES)
    if isinstance(value, str):
        return value.replace(prefix, FX)
    if isinstance(value, list):
        return [_unsub(v) for v in value]
    if isinstance(value, dict):
        return {k: _unsub(v) for k, v in value.items()}
    return value


# ---------------------------------------------------------------------------
# word-char range table (Python re \w = L* | N* | '_')
# ---------------------------------------------------------------------------

def emit_word_char_ranges() -> int:
    ranges: list[list[int]] = []
    start = -1
    prev = -2
    count = 0
    for cp in range(0x110000):
        cat = unicodedata.category(chr(cp))
        if cat[0] in ("L", "N"):
            count += 1
            if cp != prev + 1:
                if start >= 0:
                    ranges.append([start, prev])
                start = cp
            prev = cp
    if start >= 0:
        ranges.append([start, prev])
    lines = [
        "// Generated by tools/oracle/generate_prediction_contract_fixtures.py",
        "// from the real unicodedata database (same Python that freezes the",
        "// oracle). Ranges are inclusive code points whose category starts",
        "// with 'L' or 'N' — the non-underscore half of Python re \\w.",
        "// Do not edit by hand.",
        "static const std::uint32_t kWordCharRanges[][2] = {",
    ]
    lines += [f"    {{0x{a:X}, 0x{b:X}}}," for a, b in ranges]
    lines.append("};")
    lines.append(
        "static const std::size_t kWordCharRangeCount = "
        f"{len(ranges)};"
    )
    INC.write_text("\n".join(lines) + "\n", encoding="utf-8")
    assert count > 100_000, f"suspiciously few word chars: {count}"
    assert 0x5F not in {c for a, b in ranges for c in (a, b)}, "_ leaked into L/N table"
    return len(ranges)


