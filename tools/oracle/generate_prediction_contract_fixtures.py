def _well_log_obj(spec):
    """Build the attribute-bearing well_log object production passes (e.g.
    from viz.load_well_log_full_resolution): getattr() semantics mean a JSON
    object here is an attribute bag -> SimpleNamespace; a plain dict would be
    invisible to getattr and is therefore not part of the JSON contract."""
    if not isinstance(spec, dict):
        return spec
    iv = spec.get("intervals")
    iv_obj = iv
    if isinstance(iv, dict):
        iv_obj = _NS(**{
            k: ([_NS(**x) if isinstance(x, dict) else x for x in v]
                if k == "formation" and isinstance(v, list) else v)
            for k, v in iv.items()})
    return _NS(intervals=iv_obj,
               **{k: v for k, v in spec.items() if k != "intervals"})


