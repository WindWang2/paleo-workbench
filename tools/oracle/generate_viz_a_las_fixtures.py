def main() -> int:
    module = load_python_reference()
    cases = []
    fixtures = sorted(p for p in LAS_DIR.glob("*.las"))
    for path in fixtures + [A1_PATH]:
        case_id = "a1_real" if path == A1_PATH else path.stem
        text = path.read_text(encoding="utf-8", errors="replace")

        with tempfile.TemporaryDirectory() as tmp:
            tmp_path = Path(tmp) / path.name
            shutil.copyfile(path, tmp_path)
            python_result = run_python_preview(module, tmp_path, Path(tmp))
            # Negative self-check: flip single bits in the data half of the
            # file until the frozen reference changes — proves the fixture
            # is load-bearing, not satisfied by any parse of any bytes.
            negative_ok = False
            original = path.read_bytes()
            start = max(0, int(len(original) * 0.5))
            for offset in range(start, len(original)):
                corrupted = bytearray(original)
                corrupted[offset] ^= 0x01
                if bytes(corrupted) == original:
                    continue
                corrupt_path = Path(tmp) / "corrupted.las"
                corrupt_path.write_bytes(bytes(corrupted))
                corrupt_result = run_python_preview(
                    module, corrupt_path, Path(tmp))
                if corrupt_result != python_result:
                    negative_ok = True
                    break

        wle = wle_reference(text)
        wle_projection = {k: v for k, v in wle.items() if k != "verdict"}
        if wle["verdict"] == "no_curve_headers":
            # The stem is a path property; the generator knows it here and
            # the C++ test recomputes it with the same rule.
            wle_projection["summary_rows"][0][1] = path.stem

        cases.append({
            "id": case_id,
            "file": str(path.relative_to(REPO_ROOT)),
            "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
            "adjudication": ADJUDICATIONS.get(case_id, ""),
            "wle_verdict": wle["verdict"],
            "python_result": python_result,
            "wle_expected": wle_projection,
            "references_agree": python_result == wle_projection,
            "negative_self_check": negative_ok,
        })

    payload = {
        "schema": SCHEMA,
        "generated_with": {
            "lasio": _module_version("lasio"),
            "numpy": _module_version("numpy"),
            "cpp_fast_las": bool(
                sys.modules.get("paleo_workbench.viz.well_log_api")
                and sys.modules["paleo_workbench.viz.well_log_api"]
                .HAS_CPP_WELL_LOG),
            "geoviz_gitlink": "08851951f3bbc0beb90886adf52e1928f4383c16",
            "wle_gitlink": "f845e7abbbdc3133d28738975d72b2159a2d30f6",
        },
        "cases": cases,
    }
    OUT_PATH.write_text(
        json.dumps(payload, ensure_ascii=False, indent=1) + "\n",
        encoding="utf-8")
    agree = sum(1 for c in cases if c["references_agree"])
    negative = sum(1 for c in cases if c["negative_self_check"])
    print(f"wrote {OUT_PATH} ({len(cases)} cases, "
          f"references agree on {agree}, negative self-checks {negative})")
    return 0


def _module_version(name: str) -> str:
    try:
        return __import__(name).__version__
    except Exception:
        return "unavailable"


if __name__ == "__main__":
    sys.exit(main())
