#!/usr/bin/env python3
"""VIZ-A LAS preview oracle generator.

Freezes two reference results per fixture LAS file:

* ``python_result`` — the REAL production Python preview
  (paleo_workbench/resources/preview_parsers/well_log_parsers.py::las_preview
  + geoviz inspect_las_file + native_backend fast-parse fallback + lasio
  fallback). Nothing under test is stubbed; the paleo_workbench package
  __init__ (PySide6) is bypassed with import trampolines exactly like
  tests/cpp/science/fixtures/welllog/generate_oracle.py.

* ``wle_expected`` — the expectation for the C++ bridge, transcribed from
  the WLE SDK parser contract (well-log-engine/src/io/las.cpp @ f845e7ab,
  rule-by-rule citations below). WLE is the production parser shared by the
  well-log dock, so this is the normative reference for the C++ side —
  never generated by running the new C++ code.

Cases where the two references differ carry an ``adjudication`` note; the
authoritative ledger is docs/development/cpp-viz-a/reconciliation.md.

Negative self-checks:
  * every fixture's sha256 is embedded; consumers verify file integrity;
  * the generator corrupts a copy of each accepted fixture and asserts the
    Python preview changes (frozen expectations are load-bearing);
  * the C++ test flips a byte in memory and asserts the bridge result
    diverges from the frozen expectation.

Run:  python3 tools/oracle/generate_viz_a_las_fixtures.py
Out:  tests/cpp/viz_a/fixtures/las_preview_oracle.json
Deps: lasio, numpy (real reference path); geoviz from the geo-viz-engine
      submodule via PYTHONPATH (set automatically).
"""

